test "resampleBox averages the whole footprint rather than point sampling" {
    const a = testing.allocator;
    // 2x2 with four distinct opaque colours; one destination pixel must
    // be their mean. Nearest-neighbour would return a single corner.
    const src = [_]u8{
        0,   0,   0,   255, 100, 100, 100, 255,
        200, 200, 200, 255, 255, 255, 255, 255,
    };
    const out = try resampleBox(a, &src, 2, 2, 1, 1);
    defer a.free(out);
    try testing.expectEqual(@as(usize, 4), out.len);
    // (0 + 100 + 200 + 255) / 4 = 138.75 → 139
    try testing.expectEqual(@as(u8, 139), out[0]);
    try testing.expectEqual(@as(u8, 139), out[1]);
    try testing.expectEqual(@as(u8, 139), out[2]);
    try testing.expectEqual(@as(u8, 255), out[3]);
}

test "resampleBox weights partially covered source pixels" {
    const a = testing.allocator;
    // 3 source pixels → 2 destination pixels: each destination covers
    // 1.5 source pixels, so the middle one is split evenly.
    const src = [_]u8{ 0, 0, 0, 255, 100, 100, 100, 255, 200, 200, 200, 255 };
    const out = try resampleBox(a, &src, 3, 1, 2, 1);
    defer a.free(out);
    // dst0 = (0*1 + 100*0.5) / 1.5 = 33.33 → 33
    try testing.expectEqual(@as(u8, 33), out[0]);
    // dst1 = (100*0.5 + 200*1) / 1.5 = 166.67 → 167
    try testing.expectEqual(@as(u8, 167), out[4]);
}

test "resampleBox ignores the colour of fully transparent source pixels" {
    const a = testing.allocator;
    // A transparent magenta pixel next to an opaque black one: naive
    // (non-premultiplied) averaging would tint the result magenta.
    const src = [_]u8{ 0, 0, 0, 255, 255, 0, 255, 0 };
    const out = try resampleBox(a, &src, 2, 1, 1, 1);
    defer a.free(out);
    try testing.expectEqual(@as(u8, 0), out[0]);
    try testing.expectEqual(@as(u8, 0), out[1]);
    try testing.expectEqual(@as(u8, 0), out[2]);
    try testing.expectEqual(@as(u8, 128), out[3]); // 255/2 = 127.5 → 128
}

test "resampleBox rejects zero and undersized inputs" {
    const a = testing.allocator;
    const src = [_]u8{ 1, 2, 3, 4 };
    try testing.expectError(error.InvalidDimensions, resampleBox(a, &src, 0, 1, 1, 1));
    try testing.expectError(error.InvalidDimensions, resampleBox(a, &src, 1, 1, 1, 0));
    // Claims 4x4 but only one pixel of storage.
    try testing.expectError(error.InvalidDimensions, resampleBox(a, &src, 4, 4, 2, 2));
}

test "resampleNearest enlarges by an integer factor into exact pixel blocks" {
    const a = testing.allocator;
    // 2x2 checker of distinct colours → 4x4: every destination 2x2 block
    // must be a verbatim copy of one source pixel. A box resample would
    // put blended colours on the block seams.
    const src = [_]u8{
        10, 0, 0,  255, 0,  20, 0,  255,
        0,  0, 30, 255, 40, 40, 40, 255,
    };
    const out = try resampleNearest(a, &src, 2, 2, 4, 4);
    defer a.free(out);
    try testing.expectEqual(@as(usize, 4 * 4 * 4), out.len);
    for (0..4) |y| {
        for (0..4) |x| {
            const sp = ((y / 2) * 2 + (x / 2)) * 4;
            const q = (y * 4 + x) * 4;
            try testing.expectEqualSlices(u8, src[sp .. sp + 4], out[q .. q + 4]);
        }
    }
}

test "resampleNearest never invents colours on a non-integer ratio" {
    const a = testing.allocator;
    // 3 → 5 (1.666…): each output pixel must be one of the three inputs,
    // in source order, with the first and last preserved at the edges.
    const src = [_]u8{ 0, 0, 0, 255, 100, 100, 100, 255, 200, 200, 200, 255 };
    const out = try resampleNearest(a, &src, 3, 1, 5, 1);
    defer a.free(out);
    // floor(dx * 3 / 5) for dx = 0..4 → 0, 0, 1, 1, 2
    const want = [_]u8{ 0, 0, 100, 100, 200 };
    for (want, 0..) |v, i| {
        try testing.expectEqual(v, out[i * 4]);
        try testing.expectEqual(@as(u8, 255), out[i * 4 + 3]);
    }
}

test "resampleNearest rejects zero and undersized inputs like resampleBox" {
    const a = testing.allocator;
    const src = [_]u8{ 1, 2, 3, 4 };
    try testing.expectError(error.InvalidDimensions, resampleNearest(a, &src, 0, 1, 1, 1));
    try testing.expectError(error.InvalidDimensions, resampleNearest(a, &src, 1, 1, 0, 1));
    try testing.expectError(error.InvalidDimensions, resampleNearest(a, &src, 4, 4, 2, 2));
}

test "encodePng round-trips through the decoder" {
    const a = testing.allocator;
    const src = try gradientRgba(a, 64, 48);
    defer a.free(src);

    const png = try encodePng(a, src, 64, 48);
    defer a.free(png);

    // Byte-valid PNG: correct 8-byte signature...
    try testing.expect(png.len > 8);
    try testing.expectEqualSlices(u8, &.{ 0x89, 'P', 'N', 'G', '\r', '\n', 0x1a, '\n' }, png[0..8]);
    // ...and it decodes back at the requested dimensions, pixel-exact.
    const img = try decodePng(png);
    defer img.free();
