const testing = std.testing;

/// Build a `w`x`h` RGBA test image whose pixels vary in both axes, so a
/// resample that silently point-samples produces different bytes than
/// one that averages. Shared with the platform packagers' tests.
pub fn gradientRgba(allocator: std.mem.Allocator, w: usize, h: usize) ![]u8 {
    const px = try allocator.alloc(u8, w * h * 4);
    for (0..h) |y| {
        for (0..w) |x| {
            const p = (y * w + x) * 4;
            px[p + 0] = @intCast((x * 255) / (w - 1));
            px[p + 1] = @intCast((y * 255) / (h - 1));
            px[p + 2] = 128;
            px[p + 3] = 255;
        }
    }
    return px;
}

/// Assert `r.path` equals `parts` joined — built with `std.fs.path.join`
/// rather than a literal so these tests hold on Windows, where the
/// separator is `\` and a hardcoded `/` expectation would fail.
fn expectResolvedPath(a: std.mem.Allocator, r: Resolved, parts: []const []const u8) !void {
    const want = try std.fs.path.join(a, parts);
    defer a.free(want);
    try testing.expectEqualStrings(want, r.path);
}

